# --------------------------------------------------------------------------
# Small parsers
# --------------------------------------------------------------------------


def _num(text: str) -> float | None:
    value = totals.parse_amount(text)
    return float(value) if value is not None else None


def _split_quantity(text: str) -> tuple[float | None, str | None]:
    """'4,500.000 KGS' -> (4500.0, 'KGS')."""
    if not text:
        return None, None
    parts = text.split()
    number = uom = None
    for part in parts:
        value = totals.parse_amount(part)
        if value is not None and number is None:
            number = float(value)
        elif any(c.isalpha() for c in part) and uom is None:
            uom = part.strip().upper()
    return number, uom


def _percent(text: str) -> float | None:
    if not text:
        return None
    return _num(text.replace("%", " "))


def _first(*values):
    for value in values:
        if value not in (None, ""):
            return value
    return None


# --------------------------------------------------------------------------
# Reconciling the invoice total
# --------------------------------------------------------------------------


def _reconcile(candidates: dict[str, Decimal]) -> tuple[Decimal | None, list[str]]:
    """The figure the most sources agree on, and who agreed.

    With three statements of the total available, a lone disagreeing reading
    loses. With only one statement there is nothing to reconcile — it is
    returned, and the arithmetic rules downstream decide whether it holds.
    """
    if not candidates:
        return None, []
    best_value, best_sources = None, []
    for name, value in candidates.items():
        agree = [other for other, v in candidates.items()
                 if abs(v - value) <= AGREE_TOL]
        if len(agree) > len(best_sources):
            best_value, best_sources = value, agree
    return best_value, sorted(best_sources)


