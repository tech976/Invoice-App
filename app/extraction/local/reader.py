"""Assemble an `ExtractedInvoice` from the page, with no model involved.

This is a drop-in replacement for `llm.extract_invoice`: same keyword
arguments, same `ExtractionResult`. Everything downstream — persistence, the
validation rules, party matching, brokerage — is unchanged, so a bill read
here is checked exactly as hard as a bill read by a model.

The one number that must not be wrong is the invoice total, so it is not read
from a single place. The QR, the spelled-out words and the printed figure are
three independent statements of it, and the value two of them agree on is the
one that is filed.
"""
