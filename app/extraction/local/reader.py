def _party(name: str | None, gstin: str | None, address_lines: list[str],
           pages: list[PageLayout]) -> ExtractedParty:
    state_code, state_name = state_from_gstin(gstin) if gstin else (None, None)
    address = ", ".join(
        line for line in address_lines
        if line and not fields.GSTIN_RE.search(line)
        and not fields.STATE_NAME_RE.search(line)
    ) or None

    pincode = None
    for line in address_lines:
        hit = fields.PINCODE_RE.search(line)
        if hit:
            pincode = hit.group(1)
            break
    email = None
    for line in address_lines:
        hit = fields.EMAIL_RE.search(line)
        if hit:
            email = hit.group(1)
            break

    return ExtractedParty(
        name=name,
        gstin=gstin,
        pan=pan_from_gstin(gstin) if gstin else None,
        address=address,
        state_name=state_name,
        state_code=state_code,
        pincode=pincode,
        email=email,
    )


def _pick_block(blocks: list[fields.PartyBlock], role: str) -> fields.PartyBlock | None:
    for block in blocks:
        if block.role == role and (block.gstin or block.name):
            return block
    return None


